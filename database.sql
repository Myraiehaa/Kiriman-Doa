create table public.recipients (
  id bigint generated by default as identity primary key,
  display_name text not null unique check (char_length(display_name) between 1 and 60)
);

create table public.recipient_accounts (
  recipient_id bigint primary key references public.recipients(id) on delete cascade,
  user_id uuid not null unique references auth.users(id) on delete cascade
);

create table public.prayers (
  id bigint generated by default as identity primary key,
  recipient_id bigint not null references public.recipients(id) on delete restrict,
  sender_name text not null check (char_length(trim(sender_name)) between 1 and 80),
  prayer text not null check (char_length(trim(prayer)) between 1 and 3000),
  created_at timestamptz not null default now()
);

alter table public.recipients enable row level security;
alter table public.recipient_accounts enable row level security;
alter table public.prayers enable row level security;

-- Clear broad table privileges; then grant only what the client needs.
revoke all on table public.recipients from anon, authenticated;
revoke all on table public.recipient_accounts from anon, authenticated;
revoke all on table public.prayers from anon, authenticated;

grant select on table public.recipients to anon, authenticated;
grant select on table public.recipient_accounts to authenticated;
grant insert on table public.prayers to anon, authenticated;
grant select on table public.prayers to authenticated;
grant usage, select on sequence public.recipients_id_seq to anon, authenticated;
grant usage, select on sequence public.prayers_id_seq to anon, authenticated;

-- Anyone with the public form can see recipient names only.
create policy "Anyone can view recipient names"
on public.recipients for select
to anon, authenticated
using (true);

-- Signed-in users can see only their own recipient-account mapping.
create policy "Users can view their own recipient mapping"
on public.recipient_accounts for select
to authenticated
using (user_id = (select auth.uid()));

-- Public users may submit a prayer. They cannot read, update, or delete prayers.
create policy "Anyone can submit a prayer"
on public.prayers for insert
to anon, authenticated
with check (
  char_length(trim(sender_name)) between 1 and 80
  and char_length(trim(prayer)) between 1 and 3000
  and exists (
    select 1 from public.recipients r where r.id = recipient_id
  )
);

-- A recipient may read only prayers addressed to the recipient account linked to their login.
create policy "Recipients can read their own prayers"
on public.prayers for select
to authenticated
using (
  exists (
    select 1
    from public.recipient_accounts ra
    where ra.recipient_id = prayers.recipient_id
      and ra.user_id = (select auth.uid())
  )
);

